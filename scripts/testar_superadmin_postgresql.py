"""Matriz e migracao 0033 em PostgreSQL descartavel, nunca na porta oficial."""

import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app_core import auth, db, usuarios, recuperacao_senha


def main():
    if (os.environ.get('ENDEMIAS_PG_HOST') != '127.0.0.1'
            or os.environ.get('ENDEMIAS_PG_PORT', '5432') == '5432'
            or os.environ.get('ENDEMIAS_PG_DATABASE') != 'endemias_teste'):
        raise ValueError('Exige instancia descartavel e banco endemias_teste.')
    target = db.DatabaseTarget('postgresql', 'endemias_teste')
    conn = db.connect(target)
    try:
        assert conn.execute("SELECT COUNT(*) FROM pg_tables WHERE schemaname='public'").fetchone()[0] == 0
        conn.execute("""CREATE TABLE usuarios (id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            usuario TEXT UNIQUE NOT NULL,nome TEXT NOT NULL,senha_hash TEXT NOT NULL,
            nivel TEXT NOT NULL DEFAULT 'visualizador',ativo BIGINT DEFAULT 1,criado_em TEXT,
            acesso_laboratorio BIGINT DEFAULT 0,somente_laboratorio BIGINT DEFAULT 0,id_agente BIGINT,
            CONSTRAINT ck_usuarios_01 CHECK(nivel IN ('admin','operador','visualizador','usuario')))""")
        password = auth.hash_senha('SenhaFicticia123!')
        for uid, level in ((1,'admin'),(2,'admin'),(3,'admin'),(4,'usuario')):
            conn.execute("INSERT INTO usuarios(id_usuario,usuario,nome,senha_hash,nivel) VALUES (?,?,?,?,?)", (uid, f'ficticio{uid}', 'Pessoa Ficticia', password, level))
        conn.execute((ROOT / 'migrations/postgresql/0031_recuperacao_senha.sql').read_text(encoding='utf-8'))
        conn.execute((ROOT / 'migrations/postgresql/0033_superadmin.sql').read_text(encoding='utf-8'))
        conn.execute("UPDATE usuarios SET nivel='superadmin' WHERE id_usuario=1")
        conn.commit()
        try:
            conn.execute("UPDATE usuarios SET nivel='superadmin' WHERE id_usuario=2")
        except Exception:
            conn.rollback()
        else:
            raise AssertionError('Aceitou segundo superadmin')
        for uid in (1,2,3):
            try:
                usuarios.editar(target, uid, 'nivel', 'usuario', usuario_atual_id=2)
            except ValueError:
                pass
            else:
                raise AssertionError('Admin alterou conta protegida')
        usuarios.editar(target, 4, 'nivel', 'operador', usuario_atual_id=2)
        usuarios.editar(target, 3, 'id_agente', '', usuario_atual_id=1)
        for actor, uid in ((2,1),(2,3),(1,1)):
            try:
                recuperacao_senha.gerar(target, uid, actor)
            except ValueError:
                pass
            else:
                raise AssertionError('Recuperacao indevida de conta protegida')
        token = recuperacao_senha.gerar(target, 4, 2)
        assert recuperacao_senha.consumir(target, token, 'SenhaNovaFicticia!') == 4
        token = recuperacao_senha.gerar(target, 4, 2)
        usuarios.editar(target, 4, 'nivel', 'admin', usuario_atual_id=1)
        try:
            recuperacao_senha.consumir(target, token, 'OutraSenhaFicticia!')
        except ValueError:
            pass
        else:
            raise AssertionError('Link antigo alterou conta promovida')
        assert conn.execute("SELECT COUNT(*) FROM usuarios WHERE nivel='superadmin' AND ativo=1").fetchone()[0] == 1
        conn.execute("CREATE TABLE auditoria_eventos(acao TEXT,entidade TEXT,entidade_id TEXT,usuario_id BIGINT,usuario_nome TEXT,ip TEXT,detalhes_json TEXT,criado_em TEXT)")
        conn.execute("UPDATE usuarios SET nivel='admin' WHERE id_usuario=1")
        conn.commit()
        # Ensaia o bootstrap/recuperacao local em dados sinteticos, sem Agendador.
        from scripts.ativar_recuperacao_senha_windows import Release, promover_owner, connect
        from scripts.recuperar_superadmin_windows import redefinir
        configuration = {"env":dict(os.environ)}
        result = promover_owner(configuration, Release(owner_id=1, owner_login='ficticio1'))
        assert result['outras_contas_preservadas']
        raw = connect(configuration)
        try:
            redefinir(raw, 1, 'ficticio1', auth.hash_senha('SenhaLocalFicticia!'))
        finally:
            raw.close()
        conn.rollback()
        stored = conn.execute("SELECT senha_hash FROM usuarios WHERE id_usuario=1").fetchone()[0]
        assert auth.verificar_senha('SenhaLocalFicticia!', stored)[0]
        assert conn.execute("SELECT COUNT(*) FROM auditoria_eventos WHERE acao='superadmin_recuperacao_local'").fetchone()[0] == 1
        print('OK PostgreSQL descartavel: migracao 0033, superadmin unico, gestao delegada e recuperacao protegida.')
    finally:
        conn.close()


if __name__ == '__main__':
    main()
