-- Hub de formulários internos: tabela genérica de rascunho/revisão.
-- O primeiro formulário é a atualização de Registro Geográfico (RG).
CREATE TABLE formularios (
    id_formulario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_formulario text NOT NULL,
    usuario_id bigint REFERENCES usuarios(id_usuario),
    agente_nome text,
    status text NOT NULL DEFAULT 'rascunho',
    payload_json text NOT NULL,
    uuid_cliente text UNIQUE,
    revisado_por_usuario_id bigint,
    revisado_por_nome text,
    oficializado_por_usuario_id bigint,
    oficializado_por_nome text,
    motivo_devolucao text,
    criado_em text NOT NULL,
    enviado_em text,
    revisado_em text,
    oficializado_em text
);

CREATE INDEX idx_formularios_tipo_status
    ON formularios(tipo_formulario, status, id_formulario);
