CREATE TABLE pessoal_folga_creditos (
    id_credito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_agente BIGINT NOT NULL REFERENCES agentes(id_agente),
    data_aquisicao DATE NOT NULL,
    validade DATE NOT NULL CHECK (validade >= data_aquisicao),
    unidades INTEGER NOT NULL CHECK (unidades > 0),
    origem TEXT NOT NULL CHECK (origem IN ('sabado', 'domingo_feriado', 'evento_campanha',
        'servico_extraordinario', 'ajuste_administrativo', 'outro')),
    descricao TEXT NOT NULL,
    referencia TEXT,
    setor TEXT NOT NULL CHECK (setor IN ('endemias', 'ambiental')),
    criado_por BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    criado_em TEXT NOT NULL,
    cancelado_por BIGINT REFERENCES usuarios(id_usuario),
    cancelado_em TEXT,
    motivo_cancelamento TEXT,
    UNIQUE (id_credito, id_agente)
);

CREATE TABLE pessoal_ocorrencias (
    id_ocorrencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_agente BIGINT NOT NULL REFERENCES agentes(id_agente),
    data DATE NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('folga', 'falta')),
    dia_inteiro INTEGER NOT NULL CHECK (dia_inteiro IN (0, 1)),
    hora_inicio TIME,
    hora_fim TIME,
    unidades INTEGER NOT NULL,
    status TEXT NOT NULL,
    classificacao TEXT,
    observacao TEXT,
    setor TEXT NOT NULL CHECK (setor IN ('endemias', 'ambiental')),
    criado_por BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    criado_em TEXT NOT NULL,
    atualizado_por BIGINT REFERENCES usuarios(id_usuario),
    atualizado_em TEXT,
    motivo_classificacao TEXT,
    cancelado_por BIGINT REFERENCES usuarios(id_usuario),
    cancelado_em TEXT,
    motivo_cancelamento TEXT,
    CHECK ((dia_inteiro = 1 AND hora_inicio IS NULL AND hora_fim IS NULL)
        OR (dia_inteiro = 0 AND hora_inicio IS NOT NULL AND hora_fim IS NOT NULL AND hora_inicio < hora_fim)),
    CHECK ((tipo = 'folga' AND classificacao IS NULL AND unidades = dia_inteiro + 1
            AND status IN ('agendada', 'utilizada', 'cancelada'))
        OR (tipo = 'falta' AND classificacao IS NOT NULL
            AND classificacao IN ('pendente', 'justificada', 'abonada', 'injustificada')
            AND unidades = 0 AND status IN ('registrada', 'cancelada'))),
    UNIQUE (id_ocorrencia, id_agente)
);

CREATE TABLE pessoal_folga_consumos (
    id_credito BIGINT NOT NULL,
    id_ocorrencia BIGINT NOT NULL,
    id_agente BIGINT NOT NULL,
    unidades INTEGER NOT NULL CHECK (unidades IN (1, 2)),
    PRIMARY KEY (id_credito, id_ocorrencia),
    FOREIGN KEY (id_credito, id_agente) REFERENCES pessoal_folga_creditos(id_credito, id_agente),
    FOREIGN KEY (id_ocorrencia, id_agente) REFERENCES pessoal_ocorrencias(id_ocorrencia, id_agente)
);

CREATE INDEX idx_pessoal_creditos_validade ON pessoal_folga_creditos(id_agente, validade);
CREATE INDEX idx_pessoal_ocorrencias_agente_data ON pessoal_ocorrencias(id_agente, data);
CREATE INDEX idx_pessoal_ocorrencias_data ON pessoal_ocorrencias(data);
CREATE INDEX idx_pessoal_consumos_ocorrencia ON pessoal_folga_consumos(id_ocorrencia);
