ALTER TABLE pessoal_ocorrencias
    ADD COLUMN unidades_adiantadas INTEGER NOT NULL DEFAULT 0
    CHECK (unidades_adiantadas BETWEEN 0 AND unidades);

CREATE TABLE pessoal_folga_compensacoes (
    id_compensacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_agente BIGINT NOT NULL,
    id_ocorrencia BIGINT NOT NULL,
    id_credito BIGINT,
    origem TEXT NOT NULL CHECK (origem IN ('credito', 'ferias', 'dia_trabalhado')),
    unidades INTEGER NOT NULL CHECK (unidades IN (1, 2)),
    motivo TEXT NOT NULL,
    criado_por BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    criado_em TEXT NOT NULL,
    CHECK ((origem = 'credito') = (id_credito IS NOT NULL)),
    FOREIGN KEY (id_ocorrencia, id_agente) REFERENCES pessoal_ocorrencias(id_ocorrencia, id_agente),
    FOREIGN KEY (id_credito, id_agente) REFERENCES pessoal_folga_creditos(id_credito, id_agente)
);

CREATE INDEX idx_pessoal_compensacoes_ocorrencia ON pessoal_folga_compensacoes(id_ocorrencia);
CREATE INDEX idx_pessoal_compensacoes_credito ON pessoal_folga_compensacoes(id_credito);
CREATE INDEX idx_pessoal_compensacoes_agente ON pessoal_folga_compensacoes(id_agente);
