CREATE TABLE liraa_encerramentos (
    id_encerramento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ciclo BIGINT NOT NULL REFERENCES liraa_ciclos(id_ciclo) ON DELETE RESTRICT,
    encerrado_em TEXT NOT NULL,
    encerrado_por INTEGER NOT NULL,
    responsavel TEXT NOT NULL,
    observacoes TEXT NOT NULL,
    resumo_json TEXT NOT NULL,
    reaberto_em TEXT,
    reaberto_por INTEGER,
    motivo_reabertura TEXT
);

CREATE UNIQUE INDEX idx_liraa_encerramento_vigente
    ON liraa_encerramentos(id_ciclo) WHERE reaberto_em IS NULL;
